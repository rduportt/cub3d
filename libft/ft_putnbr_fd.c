#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	char	c;

	if (fd < 0)
		return ;
	if (n == -2147483648)
	{
		write((int)fd, "-2147483648", 11);
		return ;
	}
	if (n < 0)
	{
		n = -n;
		write((int)fd, "-", 1);
	}
	if (n >= 10)
		ft_putnbr_fd(n / 10, fd);
	c = n % 10 + '0';
	write((int)fd, &c, 1);
}
